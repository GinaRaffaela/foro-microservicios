WHENEVER SQLERROR EXIT SQL.SQLCODE
SET VERIFY OFF
ACCEPT users_password CHAR PROMPT 'Clave nueva de FORO_USERS: ' HIDE
ACCEPT forum_password CHAR PROMPT 'Clave nueva de FORO_FORUM: ' HIDE

CREATE USER FORO_USERS IDENTIFIED BY "&users_password"
    DEFAULT TABLESPACE USERS QUOTA 20M ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO FORO_USERS;

CREATE USER FORO_FORUM IDENTIFIED BY "&forum_password"
    DEFAULT TABLESPACE USERS QUOTA 50M ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO FORO_FORUM;

UNDEFINE users_password
UNDEFINE forum_password